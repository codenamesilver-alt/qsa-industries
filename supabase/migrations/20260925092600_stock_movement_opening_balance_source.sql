-- Adds an explicit source for the opening balances backfilled by
-- 20260925092700_stock_movement_opening_balances.sql.
--
-- A stock movement arriving from nowhere is not an adjustment, and filing it
-- under one would make the ledger read as though someone had quietly topped up
-- the stock. It gets its own label.
--
-- This is a separate migration from the backfill on purpose. Postgres will not
-- let a newly added enum value be used until the transaction that added it has
-- committed, so the value has to land in one migration and be consumed by the
-- next one.
alter type public.stock_movement_source add value if not exists 'opening_balance';
